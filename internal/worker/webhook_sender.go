package worker

import (
	"bytes"
	"context"
	"crypto/hmac"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"strconv"
	"strings"
	"time"

	"github.com/Aaditya-111/eventflow/internal/repository"
	"github.com/Aaditya-111/eventflow/internal/security"
)

const (
	maxWebhookResponseBytes = 4 * 1024
	maxWebhookRequestBytes  = 1024 * 1024
)

type WebhookSender struct {
	client   *http.Client
	resolver security.DNSResolver
	now      func() time.Time
}

type webhookEnvelope struct {
	EventID   string          `json:"event_id"`
	Type      string          `json:"type"`
	Data      json.RawMessage `json:"data"`
	CreatedAt time.Time       `json:"created_at"`
}

type WebhookResult struct {
	StatusCode int
	RetryAfter time.Duration
}

func NewWebhookSender(
	client *http.Client,
	resolver security.DNSResolver,
) (*WebhookSender, error) {
	if client == nil {
		return nil, errors.New("webhook HTTP client is required")
	}
	if resolver == nil {
		return nil, errors.New("webhook DNS resolver is required")
	}

	return &WebhookSender{
		client:   client,
		resolver: resolver,
		now:      time.Now,
	}, nil
}

// Send validates the destination immediately before sending and signs the
// exact bytes transmitted in the request body.
func (s *WebhookSender) Send(
	ctx context.Context,
	target repository.WebhookDeliveryTarget,
	event repository.Event,
	secret []byte,
) (WebhookResult, error) {
	if s == nil || s.client == nil || s.resolver == nil {
		return WebhookResult{}, errors.New("webhook sender is not configured")
	}
	if len(secret) == 0 {
		return WebhookResult{}, errors.New("webhook signing secret is empty")
	}
	if strings.TrimSpace(target.EndpointURL) == "" {
		return WebhookResult{}, errors.New("webhook endpoint URL is empty")
	}
	if strings.TrimSpace(event.EventID) == "" ||
		strings.TrimSpace(event.Type) == "" ||
		len(event.Data) == 0 ||
		!json.Valid(event.Data) {
		return WebhookResult{}, errors.New("invalid event payload")
	}

	if err := security.ValidateWebhookURL(ctx, target.EndpointURL, s.resolver); err != nil {
		return WebhookResult{}, fmt.Errorf("validate webhook destination: %w", err)
	}

	payload, err := json.Marshal(webhookEnvelope{
		EventID:   event.EventID,
		Type:      event.Type,
		Data:      event.Data,
		CreatedAt: event.CreatedAt,
	})
	if err != nil {
		return WebhookResult{}, fmt.Errorf("marshal webhook payload: %w", err)
	}
	if len(payload) > maxWebhookRequestBytes {
		return WebhookResult{}, errors.New("webhook payload exceeds size limit")
	}

	timestamp := strconv.FormatInt(s.now().Unix(), 10)
	mac := hmac.New(sha256.New, secret)
	_, _ = mac.Write([]byte(timestamp))
	_, _ = mac.Write([]byte("."))
	_, _ = mac.Write(payload)

	signature := "sha256=" + hex.EncodeToString(mac.Sum(nil))

	req, err := http.NewRequestWithContext(
		ctx,
		http.MethodPost,
		target.EndpointURL,
		bytes.NewReader(payload),
	)
	if err != nil {
		return WebhookResult{}, fmt.Errorf("create webhook request: %w", err)
	}

	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("User-Agent", "EventFlow-Webhooks/1.0")
	req.Header.Set("X-EventFlow-Event-ID", event.EventID)
	req.Header.Set("X-EventFlow-Event-Type", event.Type)
	req.Header.Set("X-EventFlow-Timestamp", timestamp)
	req.Header.Set("X-EventFlow-Signature", signature)

	resp, err := s.client.Do(req)
	if err != nil {
		return WebhookResult{}, fmt.Errorf("send webhook request: %w", err)
	}
	defer resp.Body.Close()

	// Never buffer an unbounded response from an untrusted endpoint.
	_, readErr := io.Copy(
		io.Discard,
		io.LimitReader(resp.Body, maxWebhookResponseBytes),
	)
	if readErr != nil {
		return WebhookResult{
			StatusCode: resp.StatusCode,
		}, fmt.Errorf("read webhook response: %w", readErr)
	}

	result := WebhookResult{
		StatusCode: resp.StatusCode,
	}
	if resp.StatusCode >= 200 && resp.StatusCode < 300 {
		return result, nil
	}

	if resp.StatusCode == http.StatusTooManyRequests ||
		resp.StatusCode == http.StatusServiceUnavailable {
		if seconds, parseErr := strconv.Atoi(resp.Header.Get("Retry-After")); parseErr == nil &&
			seconds > 0 {
			result.RetryAfter = time.Duration(seconds) * time.Second
		}
	}

	return result, fmt.Errorf("webhook returned HTTP %d", resp.StatusCode)
}

// VerifyWebhookSignature verifies the signature format generated by Send.
// Consumers should also enforce an acceptable timestamp age to prevent replay.
func VerifyWebhookSignature(
	secret []byte,
	timestamp string,
	body []byte,
	header string,
) bool {
	if len(secret) == 0 || timestamp == "" ||
		len(body) > maxWebhookRequestBytes ||
		!strings.HasPrefix(header, "sha256=") {
		return false
	}

	provided, err := hex.DecodeString(strings.TrimPrefix(header, "sha256="))
	if err != nil {
		return false
	}

	mac := hmac.New(sha256.New, secret)
	_, _ = mac.Write([]byte(timestamp))
	_, _ = mac.Write([]byte("."))
	_, _ = mac.Write(body)

	return hmac.Equal(provided, mac.Sum(nil))
}

const maxWebhookTimestampSkew = 5 * time.Minute

// VerifyWebhookTimestamp checks that a signed Unix timestamp is recent.
// Call this in the receiving application before processing a webhook.
func VerifyWebhookTimestamp(timestamp string, now time.Time) bool {
	if timestamp == "" {
		return false
	}

	unixTimestamp, err := strconv.ParseInt(timestamp, 10, 64)
	if err != nil {
		return false
	}

	signedAt := time.Unix(unixTimestamp, 0)
	age := now.Sub(signedAt)

	return age >= -maxWebhookTimestampSkew &&
		age <= maxWebhookTimestampSkew
}
